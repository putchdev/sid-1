"""firmware/gen/felucca_font.h from Press Start 2P (SIL OFL 1.1, assets/fonts/), an 8x8 font in the C64's style:
FONT_S a glyph 8 wide in a 16 px line, FONT_L twice the size in a 32 px line. Glyphs are 4 bits a pixel, a row
(width + 1) / 2 bytes, as gfx.c's felucca_font_t reads them.
  tools/gen_font.py path/to/PressStart2P-Regular.ttf"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FIRST, LAST = 32, 126


def glyphs(ttf):
    f = ImageFont.truetype(ttf, 8)
    out = []
    for ch in range(FIRST, LAST + 1):
        im = Image.new("1", (8, 8), 0)
        ImageDraw.Draw(im).text((0, 0), chr(ch), font=f, fill=1)
        out.append([[im.getpixel((x, y)) for x in range(8)] for y in range(8)])
    return out


def font(name, g, sx, sy, h):
    """each glyph scaled sx by sy, its 8 rows centred in a line h high"""
    w, top, data, off = 8 * sx, (h - 8 * sy) // 2, [], []
    for rows in g:
        off.append(len(data))
        for y in range(h):
            r = (y - top) // sy
            px = [15 if 0 <= r < 8 and rows[r][x // sx] else 0 for x in range(w)]
            data += [px[x] << 4 | (px[x + 1] if x + 1 < w else 0) for x in range(0, w, 2)]
    n = len(g)
    arr = lambda xs: ", ".join(map(str, xs))
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    return (f"static const uint8_t {name}_DATA[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"
            f"static const uint16_t {name}_OFF[{n}] = {{{arr(off)}}};\n"
            f"static const uint8_t {name}_ADV[{n}] = {{{arr([w] * n)}}};\n"
            f"static const uint8_t {name}_BW[{n}] = {{{arr([w] * n)}}};\n"
            f"static const felucca_font_t {name} = {{ {h}, 0, {FIRST}, {LAST}, {name}_ADV, {name}_BW, {name}_OFF, {name}_DATA }};\n")


g = glyphs(sys.argv[1])
(ROOT / "firmware/gen/felucca_font.h").write_text(
    "/* generated by tools/gen_font.py from Press Start 2P (SIL OFL 1.1, assets/fonts/PressStart2P-OFL.txt) */\n"
    "#pragma once\n#include <stdint.h>\n\n" + font("FONT_S", g, 1, 2, 16) + "\n" + font("FONT_L", g, 2, 4, 32))
